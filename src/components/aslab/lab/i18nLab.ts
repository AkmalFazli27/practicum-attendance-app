export function useLabI18n() {
  const { language } = usePreferences();
  const { t } = useTranslation('lab', { i18n: labI18n });

  useEffect(() => {
    if (labI18n.language !== language) {
      void labI18n.changeLanguage(language);
    }
  }, [language]);

  return {
    t,
    i18n: labI18n,
    language,
    isEn: language === 'en',
  };
}
